#!/usr/bin/env python3
"""Build the generated parts of the documentation site (`docs_src/`) from the repository.

Long-lived utility; doc owner: `docs/api-site.md`. Generated output is gitignored and rebuilt by
`.github/workflows/docs.yml` before `mkdocs build --strict`; `tests/test_api_site.py` runs it into a temporary directory.

What it writes, under `--out` (default `docs_src/`):

- `api-reference/*.md`: the canonical API pages `docs/api-reference/*.md` (held to the code by
  `scripts/check_api_doc_parity.py` and `tests/test_api_doc_*.py`), with each link that leaves that folder rewritten
  through `link_target()`.
- `stability.md`, `changelog.md`, `getting-started.md`: `STABILITY.md`, `CHANGELOG.md` and `docs/module.md`, with
  their links rewritten the same way.
- `cli-reference.md`: every `mathagents` subcommand and option, read from the real parser (`mathagents.cli._build_parser`).
- `explorer/api.json`: the public API as data, read by the explorer. The public modules and names come from
  `check_api_doc_parity` (the parity gate's own definition of "public"); signatures and summaries are read by AST.
- `explorer/library.json`: the proof library as data, built only through the documented `mathagents` API
  (`list_dossiers`, `dossier_status`, `result_labels`, `list_readings`, `read_fidelity_record`, `read_kernel_snapshot`,
  the registries, `STAGES`, `GATES`). No gate is re-run and nothing is re-derived: a status is the one a tracked record
  holds, labelled with the record it came from.

A link to a repository file that the site does not carry becomes a GitHub link only if its path is public
documentation (`PUBLIC_PREFIXES`); any other target, such as an internal report, fails the build.

    python3 scripts/build_api_site.py              # write docs_src/
    python3 scripts/build_api_site.py --out DIR    # write elsewhere (the tests)
"""
from __future__ import annotations

import argparse
import ast
import json
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import check_api_doc_parity as parity  # noqa: E402  (the parity gate's definition of the public surface)

REPO_URL = "https://github.com/jlcatonjr/mathAgents"
BLOB = f"{REPO_URL}/blob/main/"
API_SRC = ROOT / "docs" / "api-reference"
PKG = ROOT / "mathagents"

# Repository file -> site page, for every file the site carries.
INCLUDED = {"STABILITY.md": "stability.md", "CHANGELOG.md": "changelog.md", "docs/module.md": "getting-started.md"}
# Repository paths a site page may link to on GitHub. Anything else (docs/reports/, docs/handoffs/, workSummaries/,
# tmp/, security logs) is internal and fails the build.
PUBLIC_PREFIXES = ("docs/release-policy.md", "docs/release-checklist.md", "docs/kernel-gate.md",
                   "docs/lean-version-governance.md", "docs/lean-toolchain-upgrade.md", "docs/retrieval-surfaces.md",
                   "docs/charter/", "reports/01-methods-review.md", "reports/02-harness-spec.md", "reports/dossiers/",
                   "docs/api-site.md", "lean/", "mathagents/", "scripts/", "references/object-logics.json",
                   "references/prover-engines.json", "references/axiom-allowlist.json", "README.md", "STABILITY.md",
                   "CHANGELOG.md", "pyproject.toml")
# Never linked, even under a public prefix: operator-run tools.
INTERNAL_PREFIXES = ("scripts/operator/",)
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)\)")


class SiteError(Exception):
    """A page links to something the site cannot carry."""


def link_target(target: str, src: str, dest: str) -> str:
    """Rewrite one Markdown link from repository file `src` for the site page `dest` (both repository/site-relative)."""
    if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
        return target
    path, _, anchor = target.partition("#")
    repo = posixpath.normpath(posixpath.join(posixpath.dirname(src), path))
    page = INCLUDED.get(repo)
    if page is None and repo.startswith("docs/api-reference/") and repo.endswith(".md"):
        page = "api-reference/" + repo.rsplit("/", 1)[1]
    if page is not None:
        rel = posixpath.relpath(page, posixpath.dirname(dest) or ".")
        return rel + (f"#{anchor}" if anchor else "")
    if repo.startswith(PUBLIC_PREFIXES) and not repo.startswith(INTERNAL_PREFIXES):
        return BLOB + repo + (f"#{anchor}" if anchor else "")
    raise SiteError(f"{src}: link to {target!r} ({repo}) is not public documentation; the site cannot carry it")


def rewrite(text: str, src: str, dest: str) -> str:
    return LINK.sub(lambda m: f"[{m.group(1)}]({link_target(m.group(2), src, dest)})", text)


def generated_note(src: str) -> str:
    return (f"<!-- Generated by scripts/build_api_site.py from {src}; edit that file, not this one. -->\n")


# --- API reference pages and included pages ----------------------------------------------------------------------

def build_pages(out: Path) -> list[str]:
    written = []
    (out / "api-reference").mkdir(parents=True, exist_ok=True)
    for src in sorted(API_SRC.glob("*.md")):
        rel_src = f"docs/api-reference/{src.name}"
        dest = f"api-reference/{src.name}"
        (out / dest).write_text(generated_note(rel_src) + rewrite(src.read_text(encoding="utf-8"), rel_src, dest),
                                encoding="utf-8")
        written.append(dest)
    for rel_src, dest in INCLUDED.items():
        text = (ROOT / rel_src).read_text(encoding="utf-8")
        (out / dest).write_text(generated_note(rel_src) + rewrite(text, rel_src, dest), encoding="utf-8")
        written.append(dest)
    return written


# --- CLI reference -----------------------------------------------------------------------------------------------

def _actions(parser: argparse.ArgumentParser) -> tuple[list[argparse.Action], argparse._SubParsersAction | None]:
    acts, sub = [], None
    for a in parser._actions:  # argparse exposes no public iterator over a parser's actions
        if isinstance(a, argparse._SubParsersAction):
            sub = a
        elif not isinstance(a, argparse._HelpAction):
            acts.append(a)
    return acts, sub


def _arg_row(a: argparse.Action) -> str:
    if a.option_strings:
        name = ", ".join(f"`{o}`" for o in a.option_strings)
        if a.nargs == 0:
            kind = "flag"
        elif a.nargs in ("*", "+"):
            kind = f"`{a.metavar or a.dest.upper()} ...`"
        else:
            kind = f"`{a.metavar or a.dest.upper()}`"
    else:
        name = f"`{a.dest}`"
        kind = "rest of the command line" if a.nargs == argparse.REMAINDER else "positional"
    choices = f" One of: {', '.join(f'`{c}`' for c in a.choices)}." if a.choices else ""
    helptext = (a.help or "—").replace("|", "\\|")
    return f"| {name} | {kind} | {helptext}{choices} |"


def _command_section(path: list[str], parser: argparse.ArgumentParser, helptext: str, lines: list[str]) -> None:
    acts, sub = _actions(parser)
    if path:
        lines += [f"## `{' '.join(path)}`", "", helptext[:1].upper() + helptext[1:] + "." if helptext else "", "",
                  "```text", parser.format_usage().strip(), "```", ""]
        if acts:
            lines += ["| Argument | Takes | Description |", "|---|---|---|"] + [_arg_row(a) for a in acts] + [""]
    if sub is not None:
        helps = {c.dest: c.help or "" for c in sub._choices_actions}
        for name, child in sub.choices.items():
            _command_section(path + [name], child, helps.get(name, ""), lines)


def build_cli_reference(out: Path) -> str:
    from mathagents.cli import _build_parser

    ap = _build_parser()
    top, _ = _actions(ap)
    lines = [generated_note("mathagents/cli.py (the argparse parser)").rstrip(), "# CLI reference", "",
             "`mathagents` is the command-line entry point of the harness (`pip install -e .` installs it; "
             "`python -m mathagents.cli` runs it from a checkout). Every subcommand and option below is read from "
             "the real parser, so this page cannot drift from the code. It gives the syntax; what each command does, "
             "and how the instance root is found (`--root`, else `MATHAGENTS_ROOT`, else the nearest "
             "`mathagents.toml`), is in the [`mathagents.cli` API page](api-reference/cli.md). A dash means the "
             "parser carries no help text for that argument.", "",
             "**Exit codes:** `0` done or in sync, `1` findings, `2` usage error, `3` the architecture is switched off "
             "on this machine (see [`config`](api-reference/config.md)).", "",
             "```text", ap.format_usage().strip(), "```", "",
             "| Option | Takes | Description |", "|---|---|---|"]
    lines += [_arg_row(a) for a in top] + [""]
    _command_section([], ap, "", lines)
    (out / "cli-reference.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    return "cli-reference.md"


# --- api.json ----------------------------------------------------------------------------------------------------

def _summary(node: ast.AST) -> str:
    doc = ast.get_docstring(node) or ""
    return doc.split("\n\n", 1)[0].replace("\n", " ").strip()


def _signature(node: ast.FunctionDef) -> str:
    return f"{node.name}({ast.unparse(node.args)})" + (f" -> {ast.unparse(node.returns)}" if node.returns else "")


def _describe(tree: ast.Module, name: str) -> dict:
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name:
            return {"kind": "function", "signature": _signature(node), "summary": _summary(node), "line": node.lineno}
        if isinstance(node, ast.ClassDef) and node.name == name:
            bases = [ast.unparse(b) for b in node.bases]
            kind = "exception" if any(b.endswith(("Error", "Exception")) for b in bases) else "class"
            fields = [ast.unparse(s.target) + ": " + ast.unparse(s.annotation)
                      for s in node.body if isinstance(s, ast.AnnAssign) and isinstance(s.target, ast.Name)]
            methods = [_signature(s) for s in node.body
                       if isinstance(s, ast.FunctionDef) and not s.name.startswith("_")]
            return {"kind": kind, "signature": f"class {name}" + (f"({', '.join(bases)})" if bases else ""),
                    "summary": _summary(node), "line": node.lineno, "fields": fields, "methods": methods}
        targets = (node.targets if isinstance(node, ast.Assign)
                   else [node.target] if isinstance(node, ast.AnnAssign) else [])
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            ann = f": {ast.unparse(node.annotation)}" if isinstance(node, ast.AnnAssign) else ""
            return {"kind": "constant", "signature": f"{name}{ann}", "summary": "", "line": node.lineno}
    return {"kind": "re-export", "signature": name, "summary": "", "line": None}


def build_api_json(out: Path) -> None:
    modules = []
    for mod in parity.public_modules(PKG):
        path = PKG / f"{mod}.py"
        tree = ast.parse(path.read_text(encoding="utf-8"))
        page = "api-reference/" + mod.replace("_", "-") + ".md"
        names = []
        for name in parity.module_all(path) or []:
            entry = {"name": name, **_describe(tree, name)}
            entry["source"] = f"{BLOB}mathagents/{mod}.py" + (f"#L{entry['line']}" if entry["line"] else "")
            names.append(entry)
        modules.append({"module": f"mathagents.{mod}", "summary": _summary(tree), "page": page.replace(".md", "/"),
                        "source": f"{BLOB}mathagents/{mod}.py", "names": names})
    from mathagents import __version__

    if not __version__:
        raise SiteError("mathagents.__version__ is empty")
    _write_json(out / "explorer" / "api.json", {"schema": 1, "package": "mathagents", "version": __version__,
                                                  "modules": modules})


# --- library.json ------------------------------------------------------------------------------------------------

def _pins() -> dict:
    toolchain = (ROOT / "lean" / "lean-toolchain").read_text(encoding="utf-8").strip()
    manifest = json.loads((ROOT / "lean" / "lake-manifest.json").read_text(encoding="utf-8"))
    mathlib = next((p.get("rev", "") for p in manifest.get("packages", []) if p.get("name") == "mathlib"), "")
    if not toolchain or not mathlib:
        raise SiteError("lean/lean-toolchain or the mathlib entry of lean/lake-manifest.json is missing")
    return {"lean_toolchain": toolchain, "mathlib_rev": mathlib}


def _card(dossier: Path) -> tuple[str, dict]:
    """The dossier's title (the card's heading) and its card fields, read by the dossier gate's own reader."""
    from dossier_structure import card_fields

    f = dossier / "problem-card.md"
    text = f.read_text(encoding="utf-8") if f.is_file() else ""
    first = text.splitlines()[0] if text else ""
    title = re.sub(r"^#\s*(Problem card:\s*)?", "", first).strip() or dossier.name
    fields = card_fields(text)
    # The gate's reader takes a field's first line; mark fields whose bullet continues, so the page says so.
    lines = text.splitlines()
    continued = []
    for key in fields:
        at = next((i for i, l in enumerate(lines) if re.match(rf"^\s*[-*]\s+\*\*{re.escape(key)}:?\*\*", l, re.I)), None)
        if at is not None and at + 1 < len(lines) and re.match(r"^\s+\S", lines[at + 1]) \
                and not re.match(r"^\s*[-*]\s", lines[at + 1]):
            continued.append(key)
    return title, {"fields": fields, "continued": continued}


def gfid_check(approval_fp: str | None, snapshot_fp: str | None) -> str:
    """How a G-FID approval relates to the kernel snapshot: "matches", "differs", or "unchecked" (no snapshot row)."""
    if not snapshot_fp:
        return "unchecked"
    return "matches" if approval_fp == snapshot_fp else "differs"


def _current_source_sha256() -> str | None:
    """The G-KERNEL source hash of the Lean sources as they are now, computed by the gate's own function (the one
    `validate_dossier.py` uses to reject a stale kernel report). None when it cannot be computed."""
    import proof_integrity

    lean_dir = ROOT / "lean"
    try:
        libs, _ = proof_integrity.libraries(lean_dir)
        return proof_integrity.source_digest(lean_dir, libs)
    except Exception:  # noqa: BLE001 - shown as "unknown", never as current
        return None


def _pilots() -> dict[str, dict]:
    """Dossier slug -> pilot entry, from the pilot register (references/pilots.json, D11/D44)."""
    path = ROOT / "references" / "pilots.json"
    if not path.is_file():
        return {}
    return {p["dossier"]: p for p in json.loads(path.read_text(encoding="utf-8"))["pilots"] if p.get("dossier")}


def _dossier(root: Path, slug: str, current_sha: str | None, pilot: dict | None = None) -> dict:
    from mathagents.dossiers import dossier_status, result_labels
    from mathagents.fidelity import read_fidelity_record
    from mathagents.preferences import list_readings
    from mathagents.snapshot import read_kernel_snapshot

    status = dossier_status(root=root, slug=slug)
    snap = read_kernel_snapshot(root=root, slug=slug)
    fid = read_fidelity_record(root=root, slug=slug)
    approvals = {e.decl: e for e in fid.entries} if fid else {}
    snapshot = None
    decls: dict[str, dict] = {}
    if snap is not None:
        snapshot = {"commit": snap.commit, "checked_at": snap.checked_at, "dirty": snap.dirty,
                    "source_sha256": snap.source_sha256, "lean_version": snap.lean_version,
                    "lean_namespace": snap.lean_namespace,
                    "sources_current": (None if current_sha is None else snap.source_sha256 == current_sha)}
        for d in snap.declarations:
            decls[d.name] = {"name": d.name, "kind": d.kind, "module": d.module, "snapshot_status": d.status,
                             "axioms": list(d.axioms), "statement_fingerprint": d.statement_fingerprint,
                             "statement_uses": list(d.statement_uses)}
    for name, e in approvals.items():
        row = decls.setdefault(name, {"name": name, "kind": None, "module": None, "snapshot_status": None,
                                      "axioms": None, "statement_fingerprint": None, "statement_uses": []})
        row["gfid"] = {"status": e.status, "approver": e.approver, "date": e.date, "reading": e.reading,
                       "statement_fingerprint": e.statement_fingerprint,
                       "check": gfid_check(e.statement_fingerprint, row["statement_fingerprint"])}
    for row in decls.values():
        row.setdefault("gfid", None)
        row["source"] = _lean_file(row["module"] or ".".join(row["name"].split(".")[:2]))
    labels = [{"file": l.file, "value": l.value} for l in result_labels(root=root, slug=slug)]
    title, card = _card(status.path)
    if pilot:  # the card heading may carry an older label (D44): the register's number is the one shown
        title = re.sub(r"^P\d+\s+", "", title)
    return {
        "slug": slug,
        "pilot": pilot["id"] if pilot else None,
        "title": title,
        "card": card,
        "readings": [{"id": r.id, "title": r.title} for r in list_readings(root=root, slug=slug)],
        "result_status": labels,
        "stages_with_artifacts": list(status.stages_with_artifacts),
        "artifacts": list(status.artifacts),
        "lean_namespace": status.lean_namespace,
        "snapshot": snapshot,
        "declarations": sorted(decls.values(), key=lambda r: r["name"]),
        "files": BLOB.replace("/blob/", "/tree/") + f"reports/dossiers/{slug}",
        "problem_card": BLOB + f"reports/dossiers/{slug}/problem-card.md",
    }


def _lean_file(module: str) -> str | None:
    """GitHub link to the Lean file of a module (`MathAgents.X` or `MathAgentsWIP.X`); for a declaration not yet in a
    snapshot, its namespace's file in either library. None when no such file is tracked."""
    stem = module.split(".", 1)[1].replace(".", "/") if "." in module else module
    hits = sorted((ROOT / "lean").glob(f"MathAgents*/{stem}.lean"))
    return BLOB + hits[0].relative_to(ROOT).as_posix() if hits else None


def build_library_json(out: Path) -> None:
    from mathagents.dossiers import STAGES, list_dossiers
    from mathagents.gates import GATES
    from mathagents.registries import load_object_logics, load_prover_engines

    root = ROOT
    current = _current_source_sha256()
    slugs = list_dossiers(root=root)
    pilots = _pilots()
    if unknown := sorted(set(pilots) - set(slugs)):
        raise SiteError(f"references/pilots.json names dossiers that do not exist: {unknown}")
    allow = json.loads((root / "references" / "axiom-allowlist.json").read_text(encoding="utf-8"))
    data = {
        "schema": 1,
        "pins": _pins(),
        "stages": [{"number": s.number, "name": s.name, "agents": list(s.agents), "artifacts": list(s.artifacts)}
                   for s in STAGES],
        "gates": list(GATES),
        "object_logics": [_jsonable(e) for e in load_object_logics(root=root).entries],
        "prover_engines": [_jsonable(e) for e in load_prover_engines(root=root).entries],
        "axioms": {"base": allow.get("base_axioms", []), "approved": allow.get("approved_axioms", [])},
        "built_from": _provenance(),
        "dossiers": [_dossier(root, slug, current, pilots.get(slug)) for slug in slugs],
    }
    _write_json(out / "explorer" / "library.json", data)


def _provenance() -> dict:
    """The commit and time this data was built from (CI sets GITHUB_SHA; locally, git)."""
    import datetime
    import os
    import subprocess

    sha = os.environ.get("GITHUB_SHA") or subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                                                          capture_output=True, text=True).stdout.strip()
    return {"commit": sha or None,
            "built_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}


# --- driver ------------------------------------------------------------------------------------------------------

def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1, ensure_ascii=False, default=_jsonable) + "\n", encoding="utf-8")


def _jsonable(o):
    if isinstance(o, (tuple, set, frozenset)):
        return list(o)
    if hasattr(o, "items"):
        return dict(o)
    raise TypeError(f"not JSON-serializable: {type(o).__name__}")


def build(out: Path) -> list[str]:
    out = out.resolve()
    written = build_pages(out)
    written.append(build_cli_reference(out))
    build_api_json(out)
    build_library_json(out)
    return written + ["explorer/api.json", "explorer/library.json"]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "docs_src", help="site source directory (default docs_src/)")
    args = ap.parse_args(argv)
    try:
        written = build(args.out)
    except SiteError as e:
        print(f"build_api_site: {e}", file=sys.stderr)
        return 1
    print(f"build_api_site: wrote {len(written)} files under {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
